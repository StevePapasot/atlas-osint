export function EntityTypeLabel({ type }: { type: string }) {
  return (
    <span className="inline-flex items-center gap-1.5 text-xs text-muted">
      <EntityIcon type={type} className="h-3.5 w-3.5" />
      {ENTITY_LABELS[type as EntityType] ?? type}
    </span>
  );
}


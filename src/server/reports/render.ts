const COLORS = { ink: '#0f172a', muted: '#475569', accent: '#1d4ed8', rule: '#cbd5e1', warn: '#b45309', simulated: '#b91c1c' };

export async function renderPdf(s: ReportSnapshot): Promise<Buffer> {
  const doc = new PDFDocument({ size: 'A4', margins: { top: 56, bottom: 56, left: 56, right: 56 }, info: { Title: s.title, Author: 'ATLAS OSINT', Subject: 'Intelligence report', Creator: 'ATLAS OSINT' }, bufferPages: true });
  const chunks: Buffer[] = [];
  doc.on('data', (c: Buffer) => chunks.push(c));
  const done = new Promise<Buffer>((resolve) => doc.on('end', () => resolve(Buffer.concat(chunks))));
  const width = doc.page.width - 112;
  const clean = (t: string | null | undefined) => (t ?? '').replace(/[^\x09\x0a\x0d\x20-\x7e -ſ–—‘’“”•…→↔]/g, '?');

  const h1 = (t: string) => doc.font('Helvetica-Bold').fontSize(20).fillColor(COLORS.ink).text(clean(t), { width });
  const h2 = (t: string) => {
    if (doc.y > doc.page.height - 140) doc.addPage();
    doc.moveDown(0.8).font('Helvetica-Bold').fontSize(13).fillColor(COLORS.accent).text(clean(t), { width });
    doc.moveTo(56, doc.y + 2).lineTo(56 + width, doc.y + 2).strokeColor(COLORS.rule).lineWidth(0.5).stroke();
    doc.moveDown(0.5);
  };
  const p = (t: string, opts: { color?: string; size?: number; bold?: boolean } = {}) =>
    doc.font(opts.bold ? 'Helvetica-Bold' : 'Helvetica').fontSize(opts.size ?? 9.5).fillColor(opts.color ?? COLORS.ink).text(clean(t), { width, lineGap: 1.5 });
  const finding = (f: ReportFinding) => {
    if (doc.y > doc.page.height - 110) doc.addPage();
    p(`[${f.ref}] ${f.title}${f.isSimulated ? '  (SIMULATED)' : ''}`, { bold: true, size: 9.5 });
    p(`${claim(f.claimType)} · ${conf(f.confidence)} · ${ver(f.verification)} · ${cat(f.category)}`, { color: COLORS.muted, size: 8.5 });
    if (f.description) p(f.description, { size: 8.5 });
    if (f.geo) p(`Location: ${f.geo.place ?? `${f.geo.lat}, ${f.geo.lon}`} — ${GEO_PRECISION_LABELS[f.geo.precision as GeoPrecision] ?? f.geo.precision}. ${f.geo.basis ?? ''}`, { size: 8.5, color: COLORS.warn });
    p(`Sources: ${f.providers.join(', ')}${f.sourceUrls[0] ? ` — ${f.sourceUrls[0]}` : ''} · collected ${day(f.collectedAt)} · source date ${dateWithPrecision(f.publishedAt, f.publishedPrecision)}`, { size: 7.5, color: COLORS.muted });
    doc.moveDown(0.4);
  };
  const findings = (items: ReportFinding[], empty: string, max = 60) => {
    if (!items.length) return p(empty, { color: COLORS.muted });
    items.slice(0, max).forEach(finding);
    if (items.length > max) p(`…and ${items.length - max} more (see CSV/JSON export).`, { color: COLORS.muted });
  };

  // Cover
  doc.font('Helvetica-Bold').fontSize(10).fillColor(COLORS.accent).text('ATLAS OSINT', { characterSpacing: 2 });
  doc.moveDown(0.4);
  h1(s.title);
  doc.moveDown(0.3);
  p(`Generated ${s.generatedAt.replace('T', ' ').slice(0, 19)} UTC by ${s.generatedBy} · Investigation ${s.investigation.id}${s.options.redact ? ' · sensitive values redacted' : ''}`, { color: COLORS.muted, size: 8.5 });
  if (s.containsSimulatedData) {
    doc.moveDown(0.6);
    p('SIMULATED DEMO DATA — generated with fictional entities by ATLAS demo providers. Not intelligence.', { bold: true, color: COLORS.simulated, size: 10 });
  }

  h2('1. Executive Summary');
  s.executiveSummary.forEach((x) => { p(x); doc.moveDown(0.3); });
  if (s.aiSummary) {
    p(`AI-assisted summary (${s.aiSummary.model}); every statement cites findings. ${s.aiSummary.rejectedStatements} uncited statement(s) discarded.`, { bold: true, size: 9 });
    s.aiSummary.summary.forEach((x) => p(`• ${x.text} [${x.findingRefs.join(', ')}]`, { size: 9 }));
    s.aiSummary.hypotheses.forEach((x) => p(`• HYPOTHESIS: ${x.text} [${x.findingRefs.join(', ')}]`, { size: 9, color: COLORS.warn }));
  }

  h2('2. Scope and Methodology');
  p(`Mode: ${s.investigation.mode === 'demo' ? 'demo (simulated providers)' : 'live'} · Depth: ${s.methodology.depth} · Status: ${s.investigation.status}`);
  if (s.investigation.scope) p(`Scope: ${s.investigation.scope}`);
  p(`Confidence method: ${s.methodology.confidenceMethod}`, { size: 8.5, color: COLORS.muted });
  doc.moveDown(0.3);
  s.methodology.providers.forEach((pr) => p(`• ${pr.name} (${pr.kind}): ${pr.succeeded} succeeded, ${pr.failed} failed, ${pr.skipped} unavailable, ${pr.results} results${pr.errors[0] && pr.succeeded === 0 ? ` — ${pr.errors[0]}` : ''}`, { size: 8.5 }));

  h2('3. Target Identifiers');
  s.targets.forEach((t) => p(`• ${t.type}: ${t.value}${t.label ? ` (${t.label})` : ''}`));
  h2('4. Key Findings');
  findings(s.keyFindings, 'No findings reached moderate confidence or higher.');
  h2('5. Public Online Presence');
  findings(s.sections.onlinePresence, 'No public online presence findings.');
  h2('6. Infrastructure');
  findings(s.sections.infrastructure, 'No infrastructure findings.');
  h2('7. Geographic Findings');
  findings(s.sections.geographic, 'No geographic findings.');
  h2('8. Image Intelligence');
  findings(s.sections.imageIntelligence, 'No image analysis findings.');
  h2('9. Document Findings');
  findings(s.sections.documents, 'No document findings.');
  if (s.sections.other.length) {
    p('Other findings (breach exposure, dark-web leads, phone, cryptocurrency)', { bold: true });
    findings(s.sections.other, '', 40);
  }
  h2('10. Entity Relationships');
  if (!s.relationships.length) p('No relationships recorded.', { color: COLORS.muted });
  s.relationships.slice(0, 150).forEach((r) => p(`• ${r.from} —${r.type}→ ${r.to} (${r.status}, ${conf(r.confidence)})`, { size: 8.5 }));
  if (s.entityMatches.length) {
    doc.moveDown(0.3);
    p('Entity-resolution candidates (never merged automatically):', { bold: true, size: 9 });
    s.entityMatches.forEach((m) => p(`• ${m.a} ↔ ${m.b}: ${m.strength}, ${m.status}`, { size: 8.5 }));
  }
  h2('11. Timeline');
  if (!s.timeline.length) p('No dated events. ATLAS never invents dates.', { color: COLORS.muted });
  s.timeline.slice(0, 150).forEach((t) => p(`• ${dateWithPrecision(t.date, t.precision)} — ${t.label}${t.findingRef ? ` [${t.findingRef}]` : ''}`, { size: 8.5 }));
  h2('12. Contradictions');
  if (!s.contradictions.length) p('No conflicting attribute values were detected between sources.', { color: COLORS.muted });
  s.contradictions.forEach((c) => p(`• ${c.entityValue} — ${c.attribute}: ${c.values.map((v, j) => `"${v.value}" (${(c.providerNames[j] ?? []).join(', ')})`).join(' vs ')}`, { size: 8.5 }));
  h2('13. Confidence and Verification');
  p(Object.entries(s.stats.byConfidence).map(([k, v]) => `${conf(k)}: ${v}`).join(' · ') || 'No findings');
  p(`Analyst reviews: ${s.verification.length}; verified ${s.stats.verified}; disputed ${s.stats.disputed}; false positives ${s.stats.falsePositives}.`);
  s.verification.forEach((v) => p(`• ${v.findingRef}: ${ver(v.from)} → ${ver(v.to)} by ${v.reviewer} (${day(v.at)})${v.rationale ? ` — ${v.rationale}` : ''}`, { size: 8.5 }));
  h2('14. Unverified Leads');
  findings(s.unverifiedLeads, 'No unverified leads.', 40);
  h2('15. Limitations');
  s.limitations.forEach((l) => p(`• ${l}`, { size: 8.5 }));
  h2('16. Source References');
  s.sources.slice(0, 250).forEach((r) => p(`${r.ref}  ${r.provider} — ${r.sourceName}${r.url ? ` — ${r.url}` : ''} · collected ${day(r.collectedAt)}${r.publishedAt ? ` · source date ${day(r.publishedAt)}` : ''} · ${r.findingRefs.slice(0, 6).join(', ')}`, { size: 7.5 }));

  // Footer on every page.
  const range = doc.bufferedPageRange();
  for (let i = range.start; i < range.start + range.count; i++) {
    doc.switchToPage(i);
    const footer = `ATLAS OSINT · ${clean(s.investigation.name)}${s.containsSimulatedData ? ' · SIMULATED DATA' : ''} · page ${i + 1} of ${range.count}`;
    doc.font('Helvetica').fontSize(7).fillColor(COLORS.muted).text(footer, 56, doc.page.height - 40, { width, align: 'center', lineBreak: false });
  }
  doc.end();
  return done;
}

export async function renderReport(s: ReportSnapshot, format: ReportFormat): Promise<{ body: Buffer | string; contentType: string; extension: string }> {
  switch (format) {
    case 'markdown':
      return { body: renderMarkdown(s), contentType: 'text/markdown; charset=utf-8', extension: 'md' };
    case 'json':
      return { body: renderJson(s), contentType: 'application/json; charset=utf-8', extension: 'json' };
    case 'csv':
      return { body: renderCsv(s), contentType: 'text/csv; charset=utf-8', extension: 'csv' };
    case 'pdf':
      return { body: await renderPdf(s), contentType: 'application/pdf', extension: 'pdf' };
  }
}
